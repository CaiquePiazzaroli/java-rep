public class Aula17OperadoresDeAtribuição {
    public static void main(String[] args) {


        // Atribuição
        int x = 3; 
        System.out.println(x); // 3

        // Adição de valores
        x += 3; // mesmo que x = x + 3
        System.out.println(x); // 6

        // Subtração de valores
        x -= 3; // mesmo que x = x - 3
        System.out.println(x); // 3

        // Multiplicação de valores
        x *= 3; // mesmo que x = x * 3
        System.out.println(x); // 9

        // Divisão de valores
        x /= 3; // mesmo que x = x / 3
        System.out.println(x); // 3
     
        // Modulo do valor
        x %= 2; // mesmo que x = x % 2
        System.out.println(x); // 1

    }
}
