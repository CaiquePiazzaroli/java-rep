package Sintaxe;
public class Aula10Numbers {
    public static void main(String[] args) {

        // Grupo dos numeros inteiros
        byte byte1 = 50;
        System.out.println(byte1);


        short short1 = 30000;
        System.out.println(short1);

        int int1 = 12000000;
        System.out.println(int1);

        long long1 = 15000000000L;
        System.out.println(long1);

        //Grupo dos numeros decimais
        float float1 = 9.999f;
        System.out.println(float1);

        double double1 = 145.54654897987d;
        System.out.println(double1);


    }
}
