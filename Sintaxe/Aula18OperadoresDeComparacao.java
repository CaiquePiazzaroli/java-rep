package Sintaxe;
public class Aula18OperadoresDeComparacao {
    public static void main(String[] args) {
        int idadePessoaUm = 10;
        int idadePessoaDois = 20;

        System.out.println(idadePessoaUm == idadePessoaDois); // false
        System.out.println(idadePessoaUm < idadePessoaDois); // true
        System.out.println(idadePessoaUm > idadePessoaDois); // false
        System.out.println(idadePessoaUm <= idadePessoaDois); // true
        System.out.println(idadePessoaUm >= idadePessoaDois); // false
        System.out.println(idadePessoaUm != idadePessoaDois); // true
    }
}
