package Sintaxe;
public class Aula28LoopWhile {
    public static void main (String[] args) {
        int n1 = 0;

        while(n1 < 1000) { 
            // Exibe o valor da variável na tela
            System.out.println(n1);
            
            // Atualiza o valor da variável (muito importante)
            n1++;
        }
    }
}
