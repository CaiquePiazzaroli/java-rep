public class Main {

  public static void main(String[] args) {
    
    int nota = 5;

    nota++; // Incrementa 1 na variavel nota
    System.out.println(nota); // 6

    nota--; // Decrementa 1 na variavel nota 
    System.out.println(nota); // 5
    
    System.out.println(nota++); // 5
    System.out.println(++nota); // 6

  }
}
