public class Aula23ObjetoStringCaracteresEspeciais {
    public static void main(String[] args) {
        String frase = "Ele se dizia tão \"espertalhao\" que mal dava para ter uma conversa!";
        System.out.println(frase);

        // \n para pular linha
        String paragrafo = "Samanta tinha 4 doces \nperdeu 1 \ncom quantos ela ficou?";
        System.out.println(paragrafo);
    }
}
