package ClasseSystem;


class Aula001SystemOut {
    public static void main(String[] args) {

        // System.out é um objeto do tipo PrintStream 
        // só que dentro do objeto system
        System.out.println("Olá mundo");

        // Exibindo valroes de variaveis
        int numero = 10;
        System.out.println(numero); // 10

        // Concatenação
        System.out.println("João tem " + 72 + " anos.");

        // Fomatando a saida
        System.out.printf("Meu nome é %s e eu tenho %d anos", "caique", 45);

        


    }
}