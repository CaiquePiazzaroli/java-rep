package ClassesWrapper;

public class Aula006MenorValorEMaiorValor {
    
    
    public static void main(String[] args) {
        int maiorValorEntreDoisNumeros = Integer.max(10, 44);
        System.out.println(maiorValorEntreDoisNumeros); // 44

        int menorValorEntreDoisNumeros = Integer.min(9, 4);
        System.out.println(menorValorEntreDoisNumeros); // 4
    }



}
